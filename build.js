import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function stripExportsAndImports(code) {
  return code
    // Remove import statements
    .replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?/gm, '')
    // Remove export default
    .replace(/^export\s+default\s+/gm, '')
    // Remove export const / export function / export class
    .replace(/^export\s+(const|let|var|function|class|async\s+function)/gm, '$1')
    // Remove export { ... }
    .replace(/^export\s*\{[\s\S]*?\};?/gm, '');
}

export function buildContentBundle() {
  const filesToBundle = [
    'lib/spintax.js',
    'lib/filter-engine.js',
    'lib/ai-matcher.js',
    'content/safety.js',
    'content/dom-scanner.js',
    'content/commenter.js',
    'content/floating-widget.js',
    'content/orchestrator.js'
  ];

  let bundledSource = `/**
 * FB Job Hunter — Standalone Content Script Bundle
 * Generated by build.js — Self-contained, zero dynamic imports, CSP-proof
 */

(() => {
  'use strict';
  console.log('[FB Job Hunter] Realtime Content Script Bundle initialized.');
`;

  for (const relPath of filesToBundle) {
    const fullPath = path.join(__dirname, relPath);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`File not found: ${fullPath}`);
    }
    const content = fs.readFileSync(fullPath, 'utf8');
    const cleaned = stripExportsAndImports(content);
    bundledSource += `\n  // === Module: ${relPath} ===\n`;
    bundledSource += cleaned;
  }

  bundledSource += `\n})();\n`;

  const outputPath = path.join(__dirname, 'content/content.js');
  fs.writeFileSync(outputPath, bundledSource, 'utf8');
  console.log(`[build] Successfully generated ${outputPath} (${bundledSource.length} bytes)`);
}

// Run directly if invoked from CLI
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildContentBundle();
}
